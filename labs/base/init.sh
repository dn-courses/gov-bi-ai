#!/usr/bin/env bash
set -e

# Seed .env from the template on first start (copy-if-absent; never clobbers a student's keys).
# Owned here, not in devcontainer.json, so every entry mode gets it. A first run before .env exists
# is harmless: every compose var either carries a `:-` default or is bare passthrough, which simply
# omits an unset variable. The file is then present (bind-mounted to the host) to fill in.
[ -f .env.example ] && [ ! -f .env ] && cp .env.example .env

# Load that .env INSIDE the container, from the one path that is the same on every entry route.
# Compose's own `.env` handling cannot be relied on here: it resolves the file relative to the
# project directory (this compose file's own folder, not the repo root), so the generated justfile
# has to pass `--env-file` explicitly — and the devcontainer, which drives compose itself, has no
# way to. Without this, "Reopen in Container" gives you a workspace whose OPENAI_API_KEY is unset
# while the student's key sits in a file bind-mounted three lines away.
#
# An already-exported value wins, so `OPENAI_API_KEY=… just docs` still overrides the file. The
# profile hook repeats the load for shells that arrive later by `docker exec` — a devcontainer
# terminal, `just shell` — which inherit nothing from this script.
load_dotenv() {
  [ -f /workspace/.env ] || return 0
  while IFS= read -r line || [ -n "$line" ]; do
    line=${line#export }
    case "$line" in ''|'#'*) continue ;; esac
    case "$line" in *=*) ;; *) continue ;; esac
    key=${line%%=*}
    case "$key" in ''|*[!A-Za-z0-9_]*) continue ;; esac
    if [ -z "${!key:-}" ]; then export "$key=${line#*=}"; fi
  done < /workspace/.env
}
load_dotenv

cat > /etc/profile.d/10-workspace-dotenv.sh <<'HOOK'
# Generated by labs/base/init.sh — see the note there. Login shells only; harmless if .env is absent.
if [ -f /workspace/.env ]; then
  set -a; . /workspace/.env 2>/dev/null || true; set +a
fi
HOOK
grep -q 10-workspace-dotenv /root/.bashrc 2>/dev/null ||
  echo '. /etc/profile.d/10-workspace-dotenv.sh' >> /root/.bashrc

nohup jupyter server --no-browser --ip=0.0.0.0 --port=8888 \
  --IdentityProvider.token="${JUPYTER_TOKEN:-local-dev}" \
  --ServerApp.allow_origin="http://localhost:3000" \
  --allow-root \
  > /proc/1/fd/1 2>&1 &

# Per-lab runtime hook. Lab-specific startup wiring (ssh keypairs, cluster registration, …) lives in
# the lab that needs it — labs/<LAB>/init.sh — NOT here. base is the orchestrator: it runs that hook
# if the lab ships one. LAB is baked into the image by the Dockerfile (ARG LAB -> ENV LAB). We skip
# "base" because labs/base/init.sh is this very script. Lab hooks run on every entry and must be
# idempotent; a missing hook (most labs) is a clean no-op.
if [ "${LAB:-base}" != base ] && [ -f "labs/$LAB/init.sh" ]; then
  bash "labs/$LAB/init.sh" || echo "[init] labs/$LAB/init.sh hook failed (continuing)"
fi

# Materialize exercise stubs + sandbox scaffolds into the gitignored hands-on/ scratch area.
# This is the container's own startup command, so it runs on EVERY entry — `docker attach`/`exec`
# and bare `compose up`, not just the devcontainer postStartCommand. Copy-if-absent (see the
# script) means it's safe to re-run and never clobbers student work. Guarded because the base lab
# is also runnable from the master repo, where the generated script doesn't exist.
if [ -f scripts/materialize-hands-on.sh ]; then
  bash scripts/materialize-hands-on.sh || echo "[init] materialize-hands-on failed (continuing)"
fi

myst clean --all --yes
HOST=0.0.0.0 myst start --keep-host --port 3000 --server-port 3100
